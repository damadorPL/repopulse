#!/usr/bin/env node
// Creates a local-development `.env` at the monorepo root with freshly generated secrets.
//   pnpm env:setup                  # refuses to overwrite an existing .env
//   pnpm env:setup --force          # regenerate (stored GitHub tokens become undecryptable)
//   pnpm env:setup --github-id=Iv1.xxx --github-secret=xxx
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, ".env");

const args = Object.fromEntries(
  process.argv.slice(2).map((arg) => {
    const [key, ...rest] = arg.replace(/^--/, "").split("=");
    return [key, rest.length ? rest.join("=") : true];
  }),
);

if (existsSync(target) && !args.force) {
  console.error(`✖ ${target} already exists. Re-run with --force to overwrite it.`);
  process.exit(1);
}

const password = () => randomBytes(18).toString("base64url");
const hex32 = () => randomBytes(32).toString("hex");

const pgPassword = password();
const redisPassword = password();
const githubId = typeof args["github-id"] === "string" ? args["github-id"] : "";
const githubSecret = typeof args["github-secret"] === "string" ? args["github-secret"] : "";

const env = `# ─── RepoPulse — LOCAL DEVELOPMENT (git-ignored, never commit) ─────────────
# Generated by scripts/setup-env.mjs. Loaded automatically (non-production only) by
# apps/web/next.config.ts, packages/db/prisma.config.ts and the worker dev script;
# also read by docker compose for the dev services.
#   docker compose -f docker-compose.dev.yml up -d     # Postgres + Redis on localhost
#   pnpm --filter @repopulse/db db:migrate:deploy
#   pnpm dev                                           # http://localhost:3000

# DB/Redis URLs use 127.0.0.1, not localhost: on Windows localhost resolves to ::1 first,
# which Docker Desktop does not forward.

# ─── PostgreSQL ───────────────────────────────────────────────────────────
POSTGRES_USER=repopulse
POSTGRES_PASSWORD=${pgPassword}
POSTGRES_DB=repopulse
DATABASE_URL=postgresql://repopulse:${pgPassword}@127.0.0.1:5432/repopulse

# ─── Redis (BullMQ + SSE pub/sub) ─────────────────────────────────────────
REDIS_PASSWORD=${redisPassword}
REDIS_URL=redis://:${redisPassword}@127.0.0.1:6379

# ─── Auth.js (web) ────────────────────────────────────────────────────────
AUTH_SECRET=${hex32()}
AUTH_URL=http://localhost:3000
# Create a GitHub OAuth App: https://github.com/settings/applications/new
#   Homepage URL:               http://localhost:3000
#   Authorization callback URL: http://localhost:3000/api/auth/callback/github
AUTH_GITHUB_ID=${githubId}
AUTH_GITHUB_SECRET=${githubSecret}
# Used by docker-compose.coolify.yml for the full-stack local smoke test.
SERVICE_URL_WEB=http://localhost:3000

# ─── Token encryption (web + worker) ──────────────────────────────────────
# Changing this makes all stored GitHub tokens undecryptable (users must sign in again).
TOKEN_ENCRYPTION_KEY=${hex32()}

# ─── Worker ───────────────────────────────────────────────────────────────
POLL_INTERVAL_CRON=*/30 * * * *
# Optional: parallel repository polls / notification jobs per worker process.
# REPO_POLL_CONCURRENCY=5
# NOTIFICATION_CONCURRENCY=10
# Optional: background import of older releases (defaults shown). MAX_AGE_DAYS=0 means no age limit.
# RELEASE_BACKFILL_DEFAULT_TARGET=100
# RELEASE_BACKFILL_MAX_AGE_DAYS=365
# RELEASE_BACKFILL_HARD_CAP=1000
# RELEASE_BACKFILL_MIN_QUOTA=500

# ─── Notifications (web + worker) ─────────────────────────────────────────
# Webhooks to private or loopback addresses are blocked (SSRF guard). To reach a self-hosted
# Gotify/ntfy on the same network, allow every internal host (true) or list them (gotify,ntfy.lan).
# Link-local and cloud metadata addresses (169.254.0.0/16) stay blocked either way.
# ALLOW_INTERNAL_WEBHOOK_HOSTS=false
# Public URL for links in notifications (default: AUTH_URL / NEXTAUTH_URL).
# APP_BASE_URL=https://repopulse.example.com

# ─── Dependencies (deps-worker + deps-sandbox) ────────────────────────────
# Bearer token between deps-worker and deps-sandbox (lockfile regeneration for update PRs).
DEPS_SANDBOX_TOKEN=${hex32()}
# Optional (defaults shown). With \`pnpm dev\` the sandbox listens on port 3003 (all interfaces) without
# the container's isolation or the egress proxy: uncomment DEPS_SANDBOX_URL=http://127.0.0.1:3003 and
# set DEPS_EGRESS_PROXY= (empty) to use it.
# DEPS_SANDBOX_URL=http://deps-sandbox:3003
# DEPS_SCAN_CRON=17 * * * *
# DEPS_SCAN_CONCURRENCY=3
# DEPS_UPDATE_CONCURRENCY=1
# DEPS_HEALTH_PORT=3002
# DEPS_SANDBOX_TIMEOUT_MS=300000
`;

writeFileSync(target, env, { mode: 0o600 });
console.log(`✔ Wrote ${target} with fresh POSTGRES/REDIS passwords, AUTH_SECRET, TOKEN_ENCRYPTION_KEY and DEPS_SANDBOX_TOKEN.`);
if (!githubId || !githubSecret) {
  console.log("  Next: fill in AUTH_GITHUB_ID and AUTH_GITHUB_SECRET from your GitHub OAuth App.");
}
