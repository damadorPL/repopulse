/**
 * pip requirements files: PEP 508 lines with extras and markers, `\` continuations, `--hash` options, comments,
 * `-r` / `-c` includes (followed within the repository, cycle-safe, depth 5) and index options.
 */
import type { ParsedDependency, TextSpan } from "../types.js";
import { dirname, normalizePypiName, resolveRelativePath } from "../util.js";
import { isValidPep440Constraint, normalizePep440, parsePep440Constraint } from "../versions/pep440.js";

/** Maximum include depth for `-r` / `-c` (Slice 08 §3.2). */
export const REQUIREMENTS_MAX_INCLUDE_DEPTH = 5;

export interface RequirementHash {
  /** `"sha256:…"` as written (algorithm lowercased). */
  value: string;
  /** Span of the whole option (`--hash=sha256:…` or `--hash sha256:…`). */
  span: TextSpan;
}

export interface RequirementDependency extends ParsedDependency {
  extras: string[];
  marker: string | null;
  /** 1-based physical line where the requirement starts. */
  line: number;
  /** `--hash` options in order (empty when the line has none). */
  hashes: RequirementHash[];
  /** The `==` pin (exact version) when `declared` is a single `==` / `===` clause, else `null`. */
  pinnedVersion: string | null;
}

export interface RequirementsInclude {
  type: "requirement" | "constraint";
  /** As written after `-r` / `-c`. */
  target: string;
  /** Repo-relative resolved path, or `null` for URLs / paths outside the repository. */
  resolved: string | null;
  line: number;
}

export interface RequirementsFile {
  path: string;
  dependencies: RequirementDependency[];
  includes: RequirementsInclude[];
  /** `--index-url` value, or `null`. */
  indexUrl: string | null;
  extraIndexUrls: string[];
  /** The file starts with the `pip-compile` (or `uv pip compile`) "autogenerated" header. */
  compiled: boolean;
  /** At least one requirement carries `--hash` options. */
  hashed: boolean;
  warnings: string[];
}

const DEFAULT_INDEXES = new Set(["https://pypi.org/simple", "https://pypi.python.org/simple"]);

/** `true` for the public PyPI index URL (any trailing slash). */
export function isDefaultPypiIndex(url: string): boolean {
  return DEFAULT_INDEXES.has(url.trim().replace(/\/+$/, ""));
}

/** `true` when the first lines carry the pip-compile / uv "autogenerated" header. */
export function hasPipCompileHeader(text: string): boolean {
  const head = text.split(/\r?\n/, 12).join("\n");
  return /^#.*autogenerated by (?:pip-compile|uv)\b/im.test(head);
}

interface LogicalLine {
  /** Joined text (continuations removed, comment stripped). */
  text: string;
  /** Original offset of each character of `text`. */
  offsets: number[];
  line: number;
}

function splitLogicalLines(source: string): LogicalLine[] {
  const lines: LogicalLine[] = [];
  let current: LogicalLine | null = null;
  let offset = 0;
  let lineNumber = 0;
  while (offset <= source.length) {
    lineNumber++;
    const newline = source.indexOf("\n", offset);
    const lineEnd = newline === -1 ? source.length : newline;
    let contentEnd = lineEnd;
    if (contentEnd > offset && source[contentEnd - 1] === "\r") contentEnd--;
    const raw = source.slice(offset, contentEnd);
    const continued = raw.endsWith("\\") && !/^\s*#/.test(raw);
    const contentLength = continued ? raw.length - 1 : raw.length;
    if (!current) current = { text: "", offsets: [], line: lineNumber };
    // A comment-only line inside a continuation ends the comment, not the logical line.
    for (let i = 0; i < contentLength; i++) {
      current.text += raw[i];
      current.offsets.push(offset + i);
    }
    if (!continued) {
      lines.push(current);
      current = null;
    }
    if (newline === -1) break;
    offset = newline + 1;
  }
  if (current) lines.push(current);
  for (const line of lines) {
    const comment = /(^|\s)#/.exec(line.text);
    if (comment) {
      const cut = comment.index + (comment[1] ?? "").length;
      line.text = line.text.slice(0, cut);
      line.offsets = line.offsets.slice(0, cut);
    }
  }
  return lines;
}

/** Maps a `[start, end)` range of a logical line to an original span; `null` if it crosses a continuation. */
function toSpan(line: LogicalLine, start: number, end: number): TextSpan | null {
  if (end <= start) {
    const at = start < line.offsets.length ? line.offsets[start] : (line.offsets[line.offsets.length - 1] ?? -1) + 1;
    return at === undefined || at < 0 ? null : { start: at, end: at };
  }
  const first = line.offsets[start];
  const last = line.offsets[end - 1];
  if (first === undefined || last === undefined || last - first !== end - start - 1) return null;
  return { start: first, end: last + 1 };
}

const OPTION_ARGUMENT = /^(-r|--requirement|-c|--constraint|-e|--editable|-i|--index-url|--extra-index-url|-f|--find-links|--trusted-host)(?:=|\s+|(?<=^-[rceif]))(.*)$/;

function unsupported(
  dependency: Omit<RequirementDependency, "supported" | "unsupportedReason">,
  reason: string,
): RequirementDependency {
  return { ...dependency, supported: false, unsupportedReason: reason };
}

function eggName(text: string): string | null {
  const match = /[#&]egg=([A-Za-z0-9][A-Za-z0-9._-]*)/.exec(text);
  return match?.[1] ?? null;
}

/**
 * Parses one requirements file. Includes are listed (not followed): use {@link parseRequirementsTree} to follow
 * them. `-e`, URL and path requirements are kept as unsupported (when they have a name).
 */
export function parseRequirements(text: string, path = "requirements.txt"): RequirementsFile {
  const result: RequirementsFile = {
    path,
    dependencies: [],
    includes: [],
    indexUrl: null,
    extraIndexUrls: [],
    compiled: hasPipCompileHeader(text),
    hashed: false,
    warnings: [],
  };
  const dir = dirname(path);

  for (const line of splitLogicalLines(text)) {
    const leading = line.text.length - line.text.trimStart().length;
    const body = line.text.trim();
    if (body === "") continue;

    if (body.startsWith("-")) {
      const option = OPTION_ARGUMENT.exec(body);
      if (!option) continue; // --pre, --no-index, --require-hashes, …: no effect on the dependency list
      const flag = option[1] as string;
      const argument = (option[2] ?? "").trim();
      if (flag === "-r" || flag === "--requirement" || flag === "-c" || flag === "--constraint") {
        const isUrl = /^[a-z][a-z0-9+.-]*:\/\//i.test(argument);
        result.includes.push({
          type: flag === "-c" || flag === "--constraint" ? "constraint" : "requirement",
          target: argument,
          resolved: isUrl ? null : resolveRelativePath(dir, argument),
          line: line.line,
        });
      } else if (flag === "-i" || flag === "--index-url") result.indexUrl = argument;
      else if (flag === "--extra-index-url") result.extraIndexUrls.push(argument);
      else if (flag === "-e" || flag === "--editable") {
        const name = eggName(argument);
        if (name) {
          result.dependencies.push(
            unsupported(
              {
                name: normalizePypiName(name),
                rawName: name,
                kind: "PROD",
                group: "",
                declared: argument,
                rangeSyntax: "pep440",
                span: null,
                file: path,
                extras: [],
                marker: null,
                line: line.line,
                hashes: [],
                pinnedVersion: null,
              },
              "Editable requirement",
            ),
          );
        } else result.warnings.push(`${path}:${line.line}: editable requirement without a name skipped`);
      }
      continue;
    }

    // URL, archive or path requirement without a PEP 508 name.
    if (/^[a-z][a-z0-9+.-]*:\/\//i.test(body) || /^(?:\.{1,2}\/|\/|[A-Za-z]:\\)/.test(body) || /\.(?:whl|zip|tar\.gz|tgz|tar\.bz2)\b/i.test(body.split(/\s/)[0] ?? "")) {
      const name = eggName(body);
      if (name) {
        result.dependencies.push(
          unsupported(
            {
              name: normalizePypiName(name),
              rawName: name,
              kind: "PROD",
              group: "",
              declared: body,
              rangeSyntax: "pep440",
              span: null,
              file: path,
              extras: [],
              marker: null,
              line: line.line,
              hashes: [],
              pinnedVersion: null,
            },
            "URL or path requirement",
          ),
        );
      } else result.warnings.push(`${path}:${line.line}: URL or path requirement without a name skipped`);
      continue;
    }

    const nameMatch = /^([A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)/.exec(body);
    if (!nameMatch) {
      result.warnings.push(`${path}:${line.line}: unrecognized line skipped`);
      continue;
    }
    const rawName = nameMatch[1] as string;
    let i = rawName.length;
    const skipSpaces = (): void => {
      while (body[i] === " " || body[i] === "\t") i++;
    };
    skipSpaces();
    let extras: string[] = [];
    if (body[i] === "[") {
      const close = body.indexOf("]", i);
      if (close === -1) {
        result.warnings.push(`${path}:${line.line}: unterminated extras skipped`);
        continue;
      }
      extras = body
        .slice(i + 1, close)
        .split(",")
        .map((extra) => extra.trim())
        .filter(Boolean);
      i = close + 1;
      skipSpaces();
    }

    // Options start at whitespace + `--`; the marker at `;`.
    const optionsMatch = /\s--?[a-z]/i.exec(body.slice(i));
    const optionsStart = optionsMatch ? i + optionsMatch.index : body.length;
    const requirementPart = body.slice(i, optionsStart);
    const semicolon = requirementPart.indexOf(";");
    const specRaw = semicolon === -1 ? requirementPart : requirementPart.slice(0, semicolon);
    const marker = semicolon === -1 ? null : requirementPart.slice(semicolon + 1).trim() || null;

    const base = {
      name: normalizePypiName(rawName),
      rawName,
      kind: "PROD" as const,
      group: "",
      rangeSyntax: "pep440" as const,
      file: path,
      extras,
      marker,
      line: line.line,
      hashes: [] as RequirementHash[],
      pinnedVersion: null as string | null,
    };

    if (specRaw.trimStart().startsWith("@")) {
      result.dependencies.push(unsupported({ ...base, declared: specRaw.trim(), span: null }, "Direct URL reference"));
      continue;
    }

    // Spec text, without surrounding whitespace and optional parentheses (`requests (>=2.0)`).
    let specStart = i + (specRaw.length - specRaw.trimStart().length);
    let specEnd = i + specRaw.trimEnd().length;
    if (body[specStart] === "(" && body[specEnd - 1] === ")") {
      specStart++;
      specEnd--;
      while (body[specStart] === " ") specStart++;
      while (specEnd > specStart && body[specEnd - 1] === " ") specEnd--;
    }
    const declared = body.slice(specStart, Math.max(specStart, specEnd));
    const span = toSpan(line, leading + specStart, leading + Math.max(specStart, specEnd));

    // `--hash` options.
    const hashes: RequirementHash[] = [];
    const hashPattern = /--hash(?:=|\s+)([A-Za-z0-9]+:[A-Fa-f0-9]+)/g;
    const options = body.slice(optionsStart);
    for (let match = hashPattern.exec(options); match; match = hashPattern.exec(options)) {
      const start = leading + optionsStart + match.index;
      const hashSpan = toSpan(line, start, start + match[0].length);
      const [algorithm = "", digest = ""] = (match[1] as string).split(":");
      if (hashSpan) hashes.push({ value: `${algorithm.toLowerCase()}:${digest}`, span: hashSpan });
    }
    if (hashes.length > 0) result.hashed = true;

    const parsed = parsePep440Constraint(declared, "pep440");
    const single = parsed?.length === 1 && parsed[0]?.length === 1 ? parsed[0][0] : undefined;
    const pinnedVersion =
      single && (single.operator === "==" || single.operator === "===") && !single.wildcard
        ? normalizePep440(single.version)
        : null;
    const dependency = { ...base, declared, span, hashes, pinnedVersion };
    if (!isValidPep440Constraint(declared, "pep440")) {
      result.dependencies.push(unsupported(dependency, "Invalid version specifier"));
    } else result.dependencies.push({ ...dependency, supported: true });
  }

  if (result.indexUrl !== null && !isDefaultPypiIndex(result.indexUrl)) {
    for (const dependency of result.dependencies) {
      if (!dependency.supported) continue;
      dependency.supported = false;
      dependency.unsupportedReason = "Resolved from a custom --index-url";
    }
    result.warnings.push(`${path}: custom --index-url, dependencies are not checked`);
  }
  if (result.extraIndexUrls.some((url) => !isDefaultPypiIndex(url))) {
    result.warnings.push(`${path}: --extra-index-url is ignored; packages not on PyPI are reported as unsupported`);
  }
  return result;
}

/** `name → version` of the exact `==` pins (pip-compile output, constraint files). */
export function readRequirementsPins(text: string, path = "requirements.txt"): Map<string, string> {
  const pins = new Map<string, string>();
  for (const dependency of parseRequirements(text, path).dependencies) {
    if (dependency.pinnedVersion && !dependency.marker) pins.set(dependency.name, dependency.pinnedVersion);
    else if (dependency.pinnedVersion && !pins.has(dependency.name)) pins.set(dependency.name, dependency.pinnedVersion);
  }
  return pins;
}

export interface RequirementsTree {
  /** The root file, parsed. */
  root: RequirementsFile;
  /** Requirements of the root and of `-r` includes (each with its own `file`), in include order. */
  dependencies: RequirementDependency[];
  /** `name → version` pins from `-c` constraint files (current versions of unpinned requirements). */
  constraints: Map<string, string>;
  /** Every file read, root first. */
  files: string[];
  warnings: string[];
}

/**
 * Parses a requirements file and follows its `-r` / `-c` includes within the repository (depth ≤ 5, each file at
 * most once). `readFile` returns the text, or `null` when the file does not exist. Requirements of files listed
 * in `skipPaths` (other detected manifests) are not repeated here.
 */
export async function parseRequirementsTree(
  path: string,
  readFile: (path: string) => Promise<string | null>,
  options: { text?: string; skipPaths?: ReadonlySet<string>; maxDepth?: number } = {},
): Promise<RequirementsTree> {
  const maxDepth = options.maxDepth ?? REQUIREMENTS_MAX_INCLUDE_DEPTH;
  const visited = new Set<string>([path]);
  const warnings: string[] = [];
  const dependencies: RequirementDependency[] = [];
  const constraints = new Map<string, string>();
  const files: string[] = [path];

  const rootText = options.text ?? (await readFile(path));
  if (rootText === null) throw new Error(`${path} not found`);
  const root = parseRequirements(rootText, path);
  warnings.push(...root.warnings);
  dependencies.push(...root.dependencies);

  const visit = async (file: RequirementsFile, depth: number, asConstraint: boolean): Promise<void> => {
    for (const include of file.includes) {
      const constraint = asConstraint || include.type === "constraint";
      if (include.resolved === null) {
        warnings.push(`${file.path}:${include.line}: include "${include.target}" is outside the repository and skipped`);
        continue;
      }
      if (visited.has(include.resolved)) continue;
      if (depth >= maxDepth) {
        warnings.push(`${file.path}:${include.line}: include depth limit (${maxDepth}) reached`);
        continue;
      }
      visited.add(include.resolved);
      const text = await readFile(include.resolved);
      if (text === null) {
        warnings.push(`${file.path}:${include.line}: included file ${include.resolved} not found`);
        continue;
      }
      files.push(include.resolved);
      const parsed = parseRequirements(text, include.resolved);
      warnings.push(...parsed.warnings);
      if (constraint) {
        for (const dependency of parsed.dependencies) {
          if (dependency.pinnedVersion && !constraints.has(dependency.name)) {
            constraints.set(dependency.name, dependency.pinnedVersion);
          }
        }
      } else if (!options.skipPaths?.has(include.resolved)) dependencies.push(...parsed.dependencies);
      await visit(parsed, depth + 1, constraint);
    }
  };
  await visit(root, 0, false);
  return { root, dependencies, constraints, files, warnings };
}
