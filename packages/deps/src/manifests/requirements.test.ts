import { describe, expect, it } from "vitest";
import { hasPipCompileHeader, parseRequirements, parseRequirementsTree, readRequirementsPins } from "./requirements.js";

const H1 = "a".repeat(64);
const H2 = "b".repeat(64);

describe("parseRequirements", () => {
  it("parses PEP 508 lines with extras, markers, comments and parentheses", () => {
    const text = [
      "# comment",
      "Django==4.2.7  # pinned",
      "requests[security,socks] >= 2.31, <3 ; python_version >= '3.8'",
      "Flask_Login (>=0.6)",
      "numpy",
      "",
    ].join("\n");
    const file = parseRequirements(text, "requirements.txt");
    expect(file.dependencies.map((d) => [d.name, d.declared, d.supported])).toEqual([
      ["django", "==4.2.7", true],
      ["requests", ">= 2.31, <3", true],
      ["flask-login", ">=0.6", true],
      ["numpy", "", true],
    ]);
    const requests = file.dependencies[1]!;
    expect(requests.extras).toEqual(["security", "socks"]);
    expect(requests.marker).toBe("python_version >= '3.8'");
    expect(text.slice(requests.span!.start, requests.span!.end)).toBe(">= 2.31, <3");
    expect(file.dependencies[0]!.pinnedVersion).toBe("4.2.7");
    expect(file.dependencies[0]!.line).toBe(2);
    expect(file.dependencies[1]!.pinnedVersion).toBeNull();
  });

  it("reads hashes across continuation lines (CRLF)", () => {
    const text = `requests==2.31.0 \\\r\n    --hash=sha256:${H1} \\\r\n    --hash=sha256:${H2}\r\nidna==3.4 --hash sha256:${H1}\r\n`;
    const file = parseRequirements(text);
    expect(file.hashed).toBe(true);
    const [requests, idna] = file.dependencies;
    expect(requests!.declared).toBe("==2.31.0");
    expect(requests!.hashes.map((h) => h.value)).toEqual([`sha256:${H1}`, `sha256:${H2}`]);
    expect(text.slice(requests!.hashes[1]!.span.start, requests!.hashes[1]!.span.end)).toBe(`--hash=sha256:${H2}`);
    expect(idna!.hashes).toHaveLength(1);
    expect(idna!.line).toBe(4);
  });

  it("records includes, indexes, editable and URL requirements", () => {
    const text = [
      "-r base.txt",
      "--requirement=../shared/common.txt",
      "-c constraints.txt",
      "-rlocal.txt",
      "-e git+https://github.com/a/b.git#egg=bpkg",
      "-e .",
      "https://example.com/pkg-1.0.tar.gz#egg=urlpkg",
      "./local/path",
      "pkg @ https://example.com/pkg.whl",
      "--extra-index-url https://example.com/simple",
      "--pre",
    ].join("\n");
    const file = parseRequirements(text, "reqs/requirements.txt");
    expect(file.includes.map((i) => [i.type, i.resolved])).toEqual([
      ["requirement", "reqs/base.txt"],
      ["requirement", "shared/common.txt"],
      ["constraint", "reqs/constraints.txt"],
      ["requirement", "reqs/local.txt"],
    ]);
    expect(file.dependencies.map((d) => [d.name, d.supported])).toEqual([
      ["bpkg", false],
      ["urlpkg", false],
      ["pkg", false],
    ]);
    expect(file.extraIndexUrls).toEqual(["https://example.com/simple"]);
    expect(file.warnings.length).toBeGreaterThanOrEqual(2);
  });

  it("marks everything unsupported with a custom --index-url", () => {
    const file = parseRequirements("--index-url https://private.example.com/simple\nfoo==1.0\n");
    expect(file.dependencies[0]!.supported).toBe(false);
    expect(file.dependencies[0]!.unsupportedReason).toMatch(/index-url/);
    const pypi = parseRequirements("-i https://pypi.org/simple/\nfoo==1.0\n");
    expect(pypi.dependencies[0]!.supported).toBe(true);
  });

  it("keeps invalid specifiers as unsupported", () => {
    const file = parseRequirements("foo>=abc\n");
    expect(file.dependencies[0]).toMatchObject({ name: "foo", supported: false });
  });

  it("detects the pip-compile header", () => {
    expect(hasPipCompileHeader("#\n# This file is autogenerated by pip-compile with Python 3.12\n#\n")).toBe(true);
    expect(hasPipCompileHeader("# This file was autogenerated by uv via the following command:\n")).toBe(true);
    expect(hasPipCompileHeader("django==4\n")).toBe(false);
  });

  it("reads pins and prefers unmarked pins over marker-qualified pins", () => {
    expect([...readRequirementsPins("a==1.0\nb>=2\nC_d===3.0\n")]).toEqual([
      ["a", "1.0"],
      ["c-d", "3.0"],
    ]);
    const multi = [
      "foo==1.0 ; python_version < '3.10'",
      "foo==2.0",
      "foo==3.0 ; python_version >= '3.10'",
      "bar==4.0 ; sys_platform == 'linux'",
      "bar==5.0 ; sys_platform == 'win32'",
    ].join("\n");
    expect([...readRequirementsPins(multi)]).toEqual([
      ["foo", "2.0"],
      ["bar", "4.0"],
    ]);
  });

  it("sets span to null when specifier spans a line continuation and warns on unterminated extras", () => {
    const continued = parseRequirements("requests>=2.0,\\\n<3.0\n");
    expect(continued.dependencies[0]).toMatchObject({
      name: "requests",
      declared: ">=2.0,<3.0",
      span: null,
      supported: true,
    });

    const badExtras = parseRequirements("requests[security>=2.0\n", "requirements.txt");
    expect(badExtras.dependencies).toHaveLength(0);
    expect(badExtras.warnings[0]).toMatch(/unterminated extras/);
  });
});

describe("parseRequirementsTree", () => {
  const files: Record<string, string> = {
    "requirements.txt": "-r requirements/base.txt\n-c constraints.txt\nflask\n",
    "requirements/base.txt": "-r ../requirements.txt\n-r common.txt\nrequests==2.0\n",
    "requirements/common.txt": "-r deep1.txt\nclick==8.0\n",
    "requirements/deep1.txt": "-r deep2.txt\n",
    "requirements/deep2.txt": "-r deep3.txt\n",
    "requirements/deep3.txt": "-r deep4.txt\n",
    "requirements/deep4.txt": "-r deep5.txt\n",
    "requirements/deep5.txt": "toodeep==1.0\n",
    "constraints.txt": "flask==3.0.0\n",
  };
  const read = async (path: string): Promise<string | null> => files[path] ?? null;

  it("follows includes cycle-safe with a depth limit", async () => {
    const tree = await parseRequirementsTree("requirements.txt", read);
    expect(tree.dependencies.map((d) => `${d.file}:${d.name}`)).toEqual([
      "requirements.txt:flask",
      "requirements/base.txt:requests",
      "requirements/common.txt:click",
    ]);
    expect(tree.constraints.get("flask")).toBe("3.0.0");
    expect(tree.warnings.some((w) => w.includes("depth limit"))).toBe(true);
    expect(tree.files).toContain("requirements/deep3.txt");
    expect(tree.files).not.toContain("requirements/deep4.txt");
  });

  it("skips requirements of other manifests", async () => {
    const tree = await parseRequirementsTree("requirements.txt", read, { skipPaths: new Set(["requirements/base.txt"]) });
    expect(tree.dependencies.map((d) => d.name)).toEqual(["flask", "click"]);
  });

  it("warns about missing includes, invalid -r paths, and propagates nested -c constraints", async () => {
    const tree = await parseRequirementsTree("x.txt", async () => null, { text: "-r missing.txt\n" });
    expect(tree.warnings[0]).toMatch(/not found/);

    const nestedFiles: Record<string, string> = {
      "requirements.txt": "-r ../outside.txt\n-r https://example.com/reqs.txt\n-c constraints.txt\n",
      "constraints.txt": "-r sub-constraints.txt\nurllib3==2.2.0\n",
      "sub-constraints.txt": "certifi==2024.8.30\n",
    };
    const nestedTree = await parseRequirementsTree("requirements.txt", async (p) => nestedFiles[p] ?? null);
    expect(nestedTree.dependencies).toHaveLength(0);
    expect(nestedTree.constraints.get("urllib3")).toBe("2.2.0");
    expect(nestedTree.constraints.get("certifi")).toBe("2024.8.30");
    expect(nestedTree.warnings.filter((w) => w.includes("is outside the repository and skipped"))).toHaveLength(2);
  });
});
